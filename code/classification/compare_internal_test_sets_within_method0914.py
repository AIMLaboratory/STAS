def find_detail_sheet(xlsx_path):
    """
    Find the patient-level detail sheet automatically.
    """

    if not xlsx_path.exists():
        raise FileNotFoundError(
            f"Excel file not found:\n{xlsx_path}"
        )

    xls = pd.ExcelFile(xlsx_path)

    preferred_sheets = [
        "Detail",
        "Detailed",
        "Detailed Results",
        "Detailed_Results",
        "Case Level",
        "Case_Level",
    ]

    ordered_sheets = []

    for sheet in preferred_sheets:
        if sheet in xls.sheet_names:
            ordered_sheets.append(sheet)

    for sheet in xls.sheet_names:
        if sheet not in ordered_sheets:
            ordered_sheets.append(sheet)

    for sheet in ordered_sheets:
        df = pd.read_excel(
            xlsx_path,
            sheet_name=sheet,
        )

        if df.empty:
            continue

        y_col = try_resolve_column(
            df,
            COLUMN_ALIASES["y_true"],
        )
        model1_score = try_resolve_column(
            df,
            COLUMN_ALIASES["model1_score"],
        )
        junior_pred = try_resolve_column(
            df,
            COLUMN_ALIASES["junior_pred"],
        )
        senior_pred = try_resolve_column(
            df,
            COLUMN_ALIASES["senior_pred"],
        )

        if (
            y_col is not None
            and model1_score is not None
            and junior_pred is not None
            and senior_pred is not None
        ):
            return sheet, df

    raise RuntimeError(
        f"Could not identify a patient-level detail sheet in:\n"
        f"{xlsx_path}\n\n"
        f"Available sheets:\n{xls.sheet_names}"
    )


