# =========================================================
# 9. Metric calculation
#
# Positive class:
#     pT3-4 = 1
#
# Radiologist AUC:
#     uses ordinal radiologist score
#
# Threshold-dependent radiologist metrics:
#     use binary cT1-2 vs cT3-4 prediction
# =========================================================

def compute_metric(
    metric,
    y_true,
    y_pred,
    y_score,
):
    y_true = np.asarray(
        y_true,
        dtype=int,
    ).ravel()

    y_pred = np.asarray(
        y_pred,
        dtype=int,
    ).ravel()

    y_score = np.asarray(
        y_score,
        dtype=float,
    ).ravel()

    if metric == "AUC":
        if len(np.unique(y_true)) < 2:
            return np.nan

        return float(
            roc_auc_score(
                y_true,
                y_score,
            )
        )

    if metric == "Accuracy":
        return float(
            accuracy_score(
                y_true,
                y_pred,
            )
        )

    if metric == "Sensitivity":
        return float(
            recall_score(
                y_true,
                y_pred,
                zero_division=0,
            )
        )

    if metric == "PPV":
        return float(
            precision_score(
                y_true,
                y_pred,
                zero_division=0,
            )
        )

    if metric == "F1":
        return float(
            f1_score(
                y_true,
                y_pred,
                zero_division=0,
            )
        )

    cm = confusion_matrix(
        y_true,
        y_pred,
        labels=[0, 1],
    )

    tn, fp, fn, tp = cm.ravel()

    if metric == "Specificity":
        denominator = tn + fp

        return (
            float(tn / denominator)
            if denominator > 0
            else np.nan
        )

    if metric == "NPV":
        denominator = tn + fn

        return (
            float(tn / denominator)
            if denominator > 0
            else np.nan
        )

    raise ValueError(
        f"Unknown metric: {metric}"
    )


def compute_all_metrics(
    y_true,
    y_pred,
    y_score,
):
    return {
        metric: compute_metric(
            metric,
            y_true,
            y_pred,
            y_score,
        )
        for metric in METRICS
    }


# =========================================================
# 10. Delete-one jackknife pseudo-values
# =========================================================

def jackknife_pseudovalues(
    metric,
    y_true,
    y_pred,
    y_score,
):
    """
    Generate one pseudo-value per patient.

    pseudo_i =
        n * theta_full
        - (n - 1) * theta_without_i
    """

    y_true = np.asarray(
        y_true,
        dtype=int,
    )

    y_pred = np.asarray(
        y_pred,
        dtype=int,
    )

    y_score = np.asarray(
        y_score,
        dtype=float,
    )

    n = len(y_true)

    theta_full = compute_metric(
        metric,
        y_true,
        y_pred,
        y_score,
    )

    if not np.isfinite(theta_full):
        raise RuntimeError(
            f"Full-sample {metric} is undefined."
        )

    loo_values = np.empty(
        n,
        dtype=float,
    )

    all_indices = np.arange(n)

    for i in range(n):
        keep = all_indices != i

        value = compute_metric(
            metric,
            y_true[keep],
            y_pred[keep],
            y_score[keep],
        )

        if not np.isfinite(value):
            raise RuntimeError(
                f"{metric} became undefined after removing "
                f"case index {i}. The jackknife comparison "
                f"cannot be computed reliably."
            )

        loo_values[i] = value

    pseudo_values = (
        n * theta_full
        - (n - 1) * loo_values
    )

    return pseudo_values


# =========================================================
# 11. Compare one metric between IT1 and IT2
#     within ONE fixed method
# =========================================================

def compare_one_metric(
    method_name,
    metric,
    cohort1,
    cohort2,
):
    y1 = cohort1["y_true"]
    y2 = cohort2["y_true"]

    pred1 = (
        cohort1["methods"]
        [method_name]["pred"]
    )

    pred2 = (
        cohort2["methods"]
        [method_name]["pred"]
    )

    score1 = (
        cohort1["methods"]
        [method_name]["score"]
    )

    score2 = (
        cohort2["methods"]
        [method_name]["score"]
    )

    point1 = compute_metric(
        metric,
        y1,
        pred1,
        score1,
    )

    point2 = compute_metric(
        metric,
        y2,
        pred2,
        score2,
    )

    pseudo1 = jackknife_pseudovalues(
        metric,
        y1,
        pred1,
        score1,
    )

    pseudo2 = jackknife_pseudovalues(
        metric,
        y2,
        pred2,
        score2,
    )

    # Two-sided Welch independent-samples t-test
    test_result = ttest_ind(
        pseudo1,
        pseudo2,
        equal_var=False,
        nan_policy="raise",
    )

    return {
        "Method": method_name,
        "Metric": metric,

        "Internal test set 1":
            point1,

        "Internal test set 2":
            point2,

        "Difference (IT1 - IT2)":
            point1 - point2,

        "T statistic":
            float(test_result.statistic),

        "Raw P value":
            float(test_result.pvalue),

        "Test":
            "Two-sided Welch unpaired t-test",

        "N IT1":
            len(pseudo1),

        "N IT2":
            len(pseudo2),
    }


# =========================================================
# 12. BH correction WITHIN each method
# =========================================================

def add_within_method_bh_correction(
    df_results,
):
    """
    Apply BH correction separately within each method.

    Example:
        Model 1:
            7 raw P values -> 7 BH-adjusted P values

        Model 2:
            another 7 raw P values -> another BH correction

    No P values are pooled across different methods.
    """

    df = df_results.copy()

    df[
        "BH-adjusted P value"
    ] = np.nan

    df[
        "Significant raw P < 0.05"
    ] = False

    df[
        "Significant BH P < 0.05"
    ] = False

    for method in METHODS:
        mask = (
            df["Method"] == method
        )

        p_values = (
            df.loc[
                mask,
                "Raw P value",
            ]
            .to_numpy(
                dtype=float
            )
        )

        if len(p_values) != len(METRICS):
            raise RuntimeError(
                f"{method}: expected "
                f"{len(METRICS)} P values, "
                f"but found {len(p_values)}."
            )

        (
            reject,
            adjusted_p,
            _,
            _,
        ) = multipletests(
            p_values,
            alpha=0.05,
            method="fdr_bh",
        )

        df.loc[
            mask,
            "BH-adjusted P value",
        ] = adjusted_p

        df.loc[
            mask,
            "Significant raw P < 0.05",
        ] = (
            p_values < 0.05
        )

        df.loc[
            mask,
            "Significant BH P < 0.05",
        ] = reject

    return df


