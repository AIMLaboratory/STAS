"""
compare_internal_test_sets_within_method.py

Exploratory comparison of Internal test set 1 vs Internal test set 2.

Design
------
For each method separately:
    Model 1
    Model 2
    Model 3
    Junior Radiologist
    Senior Radiologist

compare the following seven metrics between Internal test set 1 and
Internal test set 2:
    AUC
    Accuracy
    Sensitivity
    Specificity
    PPV
    NPV
    F1

There are NO cross-model comparisons.

Statistical method
------------------
1. Read patient-level data from the Detail sheet of each evaluation workbook.
2. Recalculate each performance metric from patient-level data.
3. Generate delete-one jackknife pseudo-values for each metric.
4. Compare Internal test set 1 vs Internal test set 2 using a two-sided
   Welch independent-samples t-test.
5. Apply Benjamini-Hochberg correction SEPARATELY within each method
   across that method's seven metric-specific P values.

Therefore, each method forms its own multiplicity family of seven tests.

Interpretation
--------------
A positive difference means:
    Internal test set 1 > Internal test set 2.

The BH-adjusted P value is the P value recommended for formal statements
of statistical significance in the manuscript.

Important limitation
--------------------
Rectal filling status is completely confounded with study center in this
study design. Therefore, these between-cohort comparisons are exploratory
and cannot estimate the independent causal effect of rectal filling.
"""

