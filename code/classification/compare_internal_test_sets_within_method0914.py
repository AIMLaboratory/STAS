def normalize_column_name(name):
    """Normalize a column name for robust matching."""
    return re.sub(
        r"[^a-z0-9]+",
        "",
        str(name).strip().lower(),
    )


def try_resolve_column(df, aliases):
    """Return the matching original column name, or None."""
    normalized_to_original = {
        normalize_column_name(col): col
        for col in df.columns
    }

    for alias in aliases:
        key = normalize_column_name(alias)
        if key in normalized_to_original:
            return normalized_to_original[key]

    return None


def resolve_column(df, canonical_name):
    """Resolve one required canonical variable."""
    aliases = COLUMN_ALIASES[canonical_name]
    found = try_resolve_column(df, aliases)

    if found is None:
        raise KeyError(
            f"Unable to resolve required column '{canonical_name}'.\n"
            f"Accepted aliases:\n{aliases}\n\n"
            f"Available columns:\n{list(df.columns)}"
        )

    return found


