def to_numeric_strict(series, name):
    """Convert to numeric and reject missing/non-numeric values."""
    out = pd.to_numeric(
        series,
        errors="coerce",
    )

    if out.isna().any():
        bad_rows = (
            out[out.isna()]
            .index
            .tolist()
        )

        raise ValueError(
            f"Column '{name}' contains missing/non-numeric values "
            f"at rows:\n{bad_rows[:20]}"
        )

    return out.to_numpy()


def validate_binary(array, name):
    """Require binary values 0/1."""
    values = set(
        np.asarray(
            array,
            dtype=int,
        ).tolist()
    )

    if not values.issubset({0, 1}):
        raise ValueError(
            f"{name} contains non-binary values: "
            f"{sorted(values)}"
        )


